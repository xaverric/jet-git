const { contextBridge, ipcRenderer } = require("electron");

contextBridge.exposeInMainWorld("jetGit", {
  initial: () => ipcRenderer.invoke("repo:initial"),
  projects: () => ipcRenderer.invoke("repo:projects"),
  activate: (id) => ipcRenderer.invoke("repo:activate", id),
  chooseHost: (id) => ipcRenderer.invoke("repo:host", id),
  addHost: (name) => ipcRenderer.invoke("repo:host-add", name),
  openProject: (payload) => ipcRenderer.invoke("repo:open", payload),
  pickRepository: () => ipcRenderer.invoke("repo:pick"),
  browse: (payload) => ipcRenderer.invoke("repo:browse", payload),
  paths: (payload) => ipcRenderer.invoke("repo:paths", payload),
  loadView: (payload) => ipcRenderer.invoke("repo:view", payload),
  loadCommit: (payload) => ipcRenderer.invoke("repo:commit", payload),
  loadDiff: (payload) => ipcRenderer.invoke("repo:diff", payload),
  selection: (payload) => ipcRenderer.invoke("repo:selection", payload),
  selectionDiff: (payload) => ipcRenderer.invoke("repo:selection-diff", payload),
  checkout: (payload) => ipcRenderer.invoke("repo:checkout", payload),
  compare: (payload) => ipcRenderer.invoke("repo:compare", payload),
  compareFile: (payload) => ipcRenderer.invoke("repo:compare-file", payload),
  changes: (payload) => ipcRenderer.invoke("repo:changes", payload),
  workingDiff: (payload) => ipcRenderer.invoke("repo:working-diff", payload),
  stage: (payload) => ipcRenderer.invoke("repo:stage", payload),
  commitChanges: (payload) => ipcRenderer.invoke("repo:commit-changes", payload),
  push: (payload) => ipcRenderer.invoke("repo:push", payload),
  pull: (payload) => ipcRenderer.invoke("repo:pull", payload),
  createBranch: (payload) => ipcRenderer.invoke("repo:branch-create", payload),
  action: (payload) => ipcRenderer.invoke("repo:action", payload),
  reviewLoad: (payload) => ipcRenderer.invoke("repo:review-load", payload),
  reviewCommit: (payload) => ipcRenderer.invoke("repo:review-commit", payload),
  reviewExport: (payload) => ipcRenderer.invoke("repo:review-export", payload),
  saved: (payload) => ipcRenderer.invoke("repo:saved", payload),
  savedPatch: (payload) => ipcRenderer.invoke("repo:saved-patch", payload),
  savedApply: (payload) => ipcRenderer.invoke("repo:saved-apply", payload),
  savedDrop: (payload) => ipcRenderer.invoke("repo:saved-drop", payload),
  copyText: (text) => ipcRenderer.invoke("clip:write", text),
  settings: () => ipcRenderer.invoke("settings:get"),
  saveSettings: (patch) => ipcRenderer.invoke("settings:set", patch),
  onOpen: (listener) => ipcRenderer.on("menu:open", listener),
  onFind: (listener) => ipcRenderer.on("menu:find", listener),
  onSettings: (listener) => ipcRenderer.on("menu:settings", listener),
  onCompare: (listener) => ipcRenderer.on("menu:compare", listener),
  onUpdate: (listener) => ipcRenderer.on("menu:update", listener),
  onCommit: (listener) => ipcRenderer.on("menu:commit", listener),
  onPush: (listener) => ipcRenderer.on("menu:push", listener),
  onActions: (listener) => ipcRenderer.on("menu:actions", listener),
  onTheme: (listener) => ipcRenderer.on("settings:theme", listener),
});
